// AgileHarness MCP — onboarding / agent guidance. The remote connector exposes ~48 tools;
// without orientation the consuming agent (Claude on the phone) often can't tell which
// tool to use or how the board works. Two layers fix that, following MCP best practice:
//
//   1. SERVER INSTRUCTIONS (STORYMAP_MCP_INSTRUCTIONS) — passed to createMcpHandler and
//      returned in the `initialize` response, so EVERY client sees them automatically,
//      before any tool call. Kept short: the mental model + the rules + a pointer.
//   2. The `mcp_onboarding` TOOL (ONBOARDING_GUIDE) — the full manual (tool groups + flow
//      recipes + gotchas), fetched on demand. Belt-and-suspenders for clients that don't
//      surface server instructions prominently, and a place for depth the initialize
//      blurb shouldn't carry.
//
// Both share this one source so they never drift. Plain text (no backticks/${} — this is
// a template string).
//
// DEFERRAL IS CLIENT-SIDE (story-26xi3s). When a connector exposes many tools, the Claude
// Code harness (ToolSearch) DEFERS some tool schemas — the agent must tool_search them by
// name before it can call them. There is NO `defer` logic in this server (see register.ts):
// the server cannot "un-defer" a tool. So the lever for discoverability is purely textual —
// NAME the high-use authoring tools (update_card, save_persona, save_system, triage_finding)
// prominently here + in the gate error messages (gates.ts) so an agent finds them despite the
// deferral. The surface must NOT promise to remove a tool from the deferral (it would mislead).

