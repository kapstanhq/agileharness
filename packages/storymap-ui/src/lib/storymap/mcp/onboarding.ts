export function registerOnboarding(server: McpServer): void {
  defineTool(
    server,
    "mcp_onboarding",
    {
      title: "Onboarding — como usar este MCP",
      description:
        "LEIA PRIMEIRO. Guia completo do AgileHarness para o agente: o que é, o pipeline com gates e " +
        "autorun, TODOS os grupos de ferramentas, receitas de fluxo e princípios de trabalho. Chame no " +
        "início de uma sessão ou sempre que estiver em dúvida sobre qual tool usar e como.",
      inputSchema: {},
    },
    () => ({ content: [{ type: "text", text: ONBOARDING_GUIDE }] }),
  );
}
